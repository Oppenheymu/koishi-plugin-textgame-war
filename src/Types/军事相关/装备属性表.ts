// 装备属性表（静态配置，驻代码不落库，详见 军事系统.prompt.md 第 3 章）
// 数值锚定：1 步兵营≈1000 人、1 坦克营≈50 辆、1 炮兵营≈36 门（钢4营级参数折算）

/** 每件装备的静态属性 */
export interface 装备属性 {
    软攻: number; // 对人员杀伤
    硬攻: number; // 对装甲杀伤
    突破: number; // 进攻时的防御力
    防御: number; // 防守时的防御力
    装甲: number; // 装甲厚度（聚合用 40-60 公式，非加和）
    穿甲: number; // 穿甲厚度（同上）
    组织度: number; // 组织度贡献（加权平均用）
    HP: number; // 血量贡献
    宽度: number; // 战场宽度占用
    速度: number; // km/h
    乘员数: number; // 操作该装备所需士兵
    硬度: number; // 0~1，装甲率贡献（加权平均用）
}

