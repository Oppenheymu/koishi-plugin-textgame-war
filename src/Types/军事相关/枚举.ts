/**
 * 军衔（5级制）
 * 数值即命令优先级权重，越大越高：新命令需 ≥ 军队当前命令的军衔才能覆盖
 */
export enum 军衔 {
    少尉 = 1,
    上尉 = 2,
    少校 = 3,
    上校 = 4,
    少将 = 5,
}

export const 军衔列表: 军衔[] = [军衔.少尉, 军衔.上尉, 军衔.少校, 军衔.上校, 军衔.少将];

export const 军衔名称映射: Record<军衔, string> = {
    [军衔.少尉]: "少尉",
    [军衔.上尉]: "上尉",
    [军衔.少校]: "少校",
    [军衔.上校]: "上校",
    [军衔.少将]: "少将",
};

export function 解析军衔名称(名称: string): 军衔 | null {
    const trimmed = 名称?.trim();
    for (const 等级 of 军衔列表) {
        if (军衔名称映射[等级] === trimmed) return 等级;
    }
    return null;
}

/** 尉官级（军事路授衔允许的最高范围：将官仅可授/褫尉官） */
export const 尉官军衔列表: 军衔[] = [军衔.少尉, 军衔.上尉];

/** 军衔来源（双轨授衔 + 政体联动） */
export type 军衔来源 = "政治授予" | "军事授予" | "政体自动";

