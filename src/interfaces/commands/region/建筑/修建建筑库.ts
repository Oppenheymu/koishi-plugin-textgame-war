export const 所有建筑 = Object.values(建筑库);

export function 解析建筑类型(输入?: string): 建筑属性 | null {
    const 标准输入 = 输入?.trim();
    if (!标准输入) return null;

    return 所有建筑.find((配置) => 配置.name === 标准输入 || 配置.别名.includes(标准输入)) ?? null;
}
