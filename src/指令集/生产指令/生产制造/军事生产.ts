const 生产成功图片概率 = 0.01;
const 生产成功图片池 = [
    '军工厂3.jpg',
];

export function 军事生产(ctx: Context) {
    ctx.command('军事生产 <物品> <数量:number>').alias('军产')
        .action(async ({ session }, 物品, 数量) => {
            try {

                const { id, username, 用户资料 } = await 玩家检查(ctx, session);
                const 格式化 = (n: number) => n.toLocaleString('zh-CN');

                if ( !物品 ) {
                    return `
====[军事生产]====
□ 格式：
军事生产 <物品> <数量>
□ 可生产物品：
${Object.keys(物品库).join('、')}
`.trim();
                }

                if ( !数量 ) return '请指定要生产的数量';
                if ( 数量 <= 0 || !Number.isInteger(数量) ) return '请输入有效的数量';
                if ( 用户资料.生产次数 <= 0) return '生产次数不足';

                const 物品类型 = 物品库[物品];
                if (!物品类型) return `物品 "${物品}" 不存在。可用物品：${Object.keys(物品库).join('、')}`;

                // 验证科技
                if (用户资料.科技等级 < 物品类型.科技需求) {
                    return `科技等级不足！需要 ${物品类型.科技需求}, 现有 ${用户资料.科技等级}`;
                }

                // 计算所需资源和生产力
                const 所需生产力 = 物品类型.生产力需求 * 数量;
                const 所需钢铁 = (物品类型.资源需求.钢铁 || 0) * 数量;
                const 所需金属铝 = (物品类型.资源需求.金属铝 || 0) * 数量;
                const 工资 = 用户资料.工人 * 用户资料.工人工资;

                // 验证生产力
                const 现有生产力 = 用户资料.工人 * 用户资料.生产技术;
                if (现有生产力 < 所需生产力) {
                    return `生产力不足！需要 ${格式化(所需生产力)}, 现有 ${格式化(现有生产力)}`;
                }

                // 验证资源
                if (所需钢铁 > 0 && 用户资料.钢铁 < 所需钢铁) {
                    return `钢铁不足！需要 ${格式化(所需钢铁)}, 现有 ${格式化(用户资料.钢铁)}`;
                }
                if (所需金属铝 > 0 && 用户资料.金属铝 < 所需金属铝) {
                    return `金属铝不足！需要 ${格式化(所需金属铝)}, 现有 ${格式化(用户资料.金属铝)}`;
                }

                // 构建消耗明细
                const 消耗明细: string[] = [];
                if (所需钢铁 > 0) 消耗明细.push(`■ 钢铁：-${格式化(所需钢铁)}`);
                if (所需金属铝 > 0) 消耗明细.push(`■ 金属铝：-${格式化(所需金属铝)}`);
                消耗明细.push(`■ 生活资料：-${格式化(工资)}`);

                // 获取物品对应的属性名
                const 属性名 = 物品属性名[物品];
                if (!属性名) return '物品属性映射错误';

                // 计算更新数据
                const 更新数据: Partial<Player> = {
                    钢铁: 用户资料.钢铁 - 所需钢铁,
                    金属铝: 用户资料.金属铝 - 所需金属铝,
                    生活资料: 用户资料.生活资料 - 工资,
                    生产次数: 用户资料.生产次数 - 1,
                };

                // 添加生产的物品
                (更新数据 as any)[属性名] = (用户资料[属性名] as number || 0) + 数量;

                // 保存到数据库
                await ctx.database.set('malieplayer', { id: id }, 更新数据);

                await 尝试发送随机图片(session, 生产成功图片池, 生产成功图片概率);

                return `
====[军事生产]====
${username} 同志：
成功生产 ${数量} 个 ${物品类型.name}
${消耗明细.join('\n')}
`.trim();

            } catch (error) {
                return (error as Error).message;
            }
        });
}
