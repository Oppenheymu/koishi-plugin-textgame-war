import { Context } from 'koishi';
import { requirePlayer } from "../../Utils/index";

export function 提升科技(ctx: Context) {
    ctx.command('提升科技 <生活资料:number>')
        .action(async ({ session }, 投入生活资料) => {
            try {
                const { userId, username } = await requirePlayer(ctx, session);
                const 用户资料 = (await ctx.database.get('malieplayer', { userId }))[0]!;

                // 验证输入
                if (!投入生活资料 || 投入生活资料 <= 0) {
                    return '请输入有效的生活资料数量！\n例如：提升科技 10000';
                }

                // 检查生活资料是否足够
                if (用户资料.生活资料 < 投入生活资料) {
                    return `生活资料不足！当前拥有：${用户资料.生活资料}，需要：${投入生活资料}`;
                }

                // 检查是否已达到科技上限
                if (用户资料.科技等级 >= 3000) {
                    return '科技已达到上限（3000级），无法继续提升！';
                }

                // 扣除生活资料
                const 减少后的生活资料 = 用户资料.生活资料 - 投入生活资料;
                let 增加后的科技池投入 = 用户资料.科技池投入 + 投入生活资料;
                let 新科技等级 = 用户资料.科技等级;

                // 计算升级：C(n) = 5000 × (n - 4)，这是从 n 级升到 n+1 级所需容量
                let 升级次数 = 0;
                while (新科技等级 < 3000) {
                    const 所需容量 = 5000 * (新科技等级 - 4);
                    
                    if (所需容量 <= 0) {
                        return `科技等级异常，无法提升！`;
                    }
                    
                    if (增加后的科技池投入 >= 所需容量) {
                        增加后的科技池投入 -= 所需容量;
                        新科技等级 += 1;
                        升级次数 += 1;
                    } else {
                        break;
                    }
                }
                
                // 计算新的科技池容量（升到下一级所需容量）
                const 新的科技池容量 = 新科技等级 < 3000 ? 5000 * (新科技等级 - 4) : 0;

                // 更新数据库
                await ctx.database.set('malieplayer', { userId }, {
                    生活资料: 减少后的生活资料,
                    科技池投入: 增加后的科技池投入,
                    科技等级: 新科技等级,
                    科技池容量: 新的科技池容量
                });

                // 构建返回信息
                const 科技池百分比 = 新的科技池容量 > 0 
                    ? Math.floor((增加后的科技池投入 / 新的科技池容量) * 100)
                    : 0;
                const 旧科技池百分比 = 用户资料.科技池容量 > 0 
                    ? Math.floor((用户资料.科技池投入 / 用户资料.科技池容量) * 100)
                    : 0;
                const 百分比增长 = 科技池百分比 - 旧科技池百分比;

                let 返回信息 = `【科技】
${username}同志：`;

                if (升级次数 > 0) {
                    返回信息 += `
==成功投入科技生产==
■科技级别：${用户资料.科技等级}→${新科技等级}(+${升级次数}级)
■科技池：${科技池百分比}%(${百分比增长 > 0 ? '+' : ''}${百分比增长}%)
■生活资料：${减少后的生活资料}(-${投入生活资料})`;
                } else {
                    返回信息 += `
==成功投入科技生产==
■科技池：${科技池百分比}%(${百分比增长 > 0 ? '+' : ''}${百分比增长}%)
■生活资料：${减少后的生活资料}(-${投入生活资料})`;
                }

                return 返回信息.trim();

            } catch (error) {
                return (error as Error).message;
            }
        });
}
