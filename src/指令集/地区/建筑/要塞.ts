import type { Context } from 'koishi';
import type { Fortress } from '@/types';
import { 更新地区战略资料 } from '@/utils';
import { 堡垒升级库 } from './config';
import {
    执行资源与工资结算,
    执行预检查,
    格式化,
    组装消耗文本,
    解析轮次,
    计算最大可执行轮次,
} from './utils';

export function 修建地区堡垒(ctx: Context) {
    ctx.command('修建地区堡垒 [轮次:number]')
        .alias('升级地区堡垒')
        .alias('修建堡垒')
        .alias('升级堡垒')
        .action(async ({ session }, 轮次输入) => {
            try {
                const {
                    id,
                    username,
                    地区编号,
                    展示地区名称,
                    地区战略资料,
                    用户资料,
                } = await 执行预检查(ctx, session, '修建地区堡垒');

                const 轮次 = 解析轮次(轮次输入);
                if (轮次 <= 0) {
                    return '请输入有效轮次（正整数）';
                }

                // 计算当前等级（从堡垒名称映射到数字）
                const 堡垒名称表: Record<Fortress, number> = {
                    一级要塞: 1,
                    二级要塞: 2,
                    三级要塞: 3,
                    四级要塞: 4,
                    五级要塞: 5,
                    六级要塞: 6,
                    七级要塞: 7,
                };
                const 当前堡垒 = 地区战略资料.地区堡垒;
                const 当前等级 = 当前堡垒 ? 堡垒名称表[当前堡垒] : 0;
                const 目标等级 = 当前等级 + 1;
                const 升级配置 = 堡垒升级库[目标等级];

                if (!升级配置) {
                    return `地区堡垒已达最高等级（Lv.${格式化(当前等级)}）`;
                }

                if (用户资料.科技等级 < 升级配置.科技需求) {
                    return `科技等级不足，升级到堡垒 Lv.${目标等级} 需要科技等级 ${格式化(升级配置.科技需求)}`;
                }

                // 使用通用的最大轮次计算
                const 最大可执行轮次 = 计算最大可执行轮次(
                    用户资料,
                    升级配置.资源需求,
                    轮次
                );

                if (最大可执行轮次 <= 0) {
                    return '资源或生活资料不足，无法完成任意一轮修建';
                }

                // 简化逻辑：直接升级，不跟踪中间进度
                const 单轮生产力 = 用户资料.工人 * 用户资料.生产技术;
                const 投入总生产力 = 单轮生产力 * 最大可执行轮次;
                const 是否有足够生产力 = 投入总生产力 >= 升级配置.生产力需求;
                const 实际轮次 = 是否有足够生产力
                    ? 最大可执行轮次
                    : 最大可执行轮次;

                const { 工资消耗, 资源消耗 } = await 执行资源与工资结算(
                    ctx,
                    id,
                    用户资料,
                    实际轮次,
                    升级配置.资源需求
                );

                // 只有生产力足够时才升级
                if (是否有足够生产力) {
                    const 等级表: Record<number, Fortress> = {
                        1: '一级要塞',
                        2: '二级要塞',
                        3: '三级要塞',
                        4: '四级要塞',
                        5: '五级要塞',
                        6: '六级要塞',
                        7: '七级要塞',
                    };
                    const 新堡垒 = 等级表[目标等级];
                    await 更新地区战略资料(ctx, 地区编号, {
                        地区堡垒: 新堡垒,
                    });
                }

                return [
                    '====[征战文游]====',
                    `${username} 同志：`,
                    `■ 地区：${展示地区名称}（${地区编号}）`,
                    `■ 堡垒等级：Lv.${格式化(当前等级)} → Lv.${格式化(
                        是否有足够生产力 ? 目标等级 : 当前等级
                    )}`,
                    `■ 目标升级：Lv.${格式化(目标等级)}`,
                    `■ 科技需求：${格式化(升级配置.科技需求)}`,
                    `■ 本次投入生产力：${格式化(投入总生产力)}`,
                    `■ 工资消耗：${格式化(工资消耗)}`,
                    ...组装消耗文本(资源消耗),
                    `■ 状态：${是否有足够生产力 ? '升级完成' : '生产力不足，未升级'}`,
                ].join('\n');
            } catch (error) {
                return (error as Error).message;
            }
        });
}
