const 所有建筑 = Object.values(建筑库);

function 解析建筑类型(输入?: string): 建筑属性 | null {
    const 标准输入 = 输入?.trim();
    if (!标准输入) return null;

    return 所有建筑.find((配置) => 配置.name === 标准输入 || 配置.别名.includes(标准输入)) ?? null;
}

export function 修建地区建筑(ctx: Context) {
    ctx.command('修建地区建筑 <建筑类型:string> [轮次:number]')
        .alias('地区修建')
        .alias('建造地区建筑')
        .alias('建造')
        .alias('修建')
        .action(async ({ session }, 建筑类型输入, 轮次输入) => {
            try {
                const { id, username, 当前驻扎地区, 地区编号, 展示地区名称, 地区资料 } =
                    await 驻扎检查(ctx, session);
                const { 用户资料 } = await 玩家检查(ctx, session);

                if (当前驻扎地区 !== 地区编号) {
                    return `你当前驻扎在 ${当前驻扎地区 || '未驻扎地区'}，仅驻扎在本地区的玩家可修建地区建筑`;
                }

                const 建筑属性 = 解析建筑类型(建筑类型输入);
                if (!建筑属性) {
                    return [
                        '=====[地区建筑]=====',
                        '格式：修建地区建筑 <建筑类型> [轮次]',
                        `支持：${所有建筑.map((项) => 项.name).join('/')}`,
                        '说明：每轮按当前生产力修建，消耗工资、资源与生产次数',
                    ].join('\n');
                }

                const 轮次 = Number.isFinite(轮次输入) ? Math.floor(轮次输入 as number) : 1;
                if (轮次 <= 0) {
                    return '请输入有效轮次（正整数）';
                }

                if (用户资料.科技等级 < 建筑属性.科技需求) {
                    return `科技等级不足，修建${建筑属性.显示名}需要科技等级 ${建筑属性.科技需求}`;
                }

                if (用户资料.生产次数 <= 0) {
                    return '生产次数不足';
                }

                const 当前值 =
                    (地区资料[建筑属性.当前字段 as keyof typeof 地区资料] as number) ?? 0;
                const 上限值 =
                    (地区资料[建筑属性.上限字段 as keyof typeof 地区资料] as number) ?? 0;

                if (当前值 >= 上限值) {
                    return `${建筑属性.显示名}已达上限（${格式化(当前值)} / ${格式化(上限值)}）`;
                }

                const 单轮生产力 = 用户资料.工人 * 用户资料.生产技术;
                if (单轮生产力 <= 0) {
                    return '当前生产力为零，无法修建';
                }

                if (单轮生产力 < 建筑属性.生产力需求) {
                    return `单轮生产力不足，修建${建筑属性.显示名}每轮至少需要 ${格式化(建筑属性.生产力需求)} 生产力`;
                }

                // 使用通用的最大轮次计算
                const 最大可执行轮次 = 计算最大可执行轮次(用户资料, 建筑属性.资源需求, 轮次);

                if (最大可执行轮次 <= 0) {
                    return '资源或生活资料不足，无法完成任意一轮修建';
                }

                const 单轮工资 = 用户资料.工人 * 用户资料.工人工资;
                const 剩余容量 = Math.max(0, 上限值 - 当前值);
                const 达到上限所需轮次 = Math.ceil(剩余容量 / 单轮生产力);
                const 实际轮次 = Math.min(最大可执行轮次, 达到上限所需轮次);
                const 增量 = Math.min(剩余容量, 单轮生产力 * 实际轮次);

                if (增量 <= 0) {
                    return `${建筑属性.显示名}已达上限（${格式化(当前值)} / ${格式化(上限值)}）`;
                }

                const 工资消耗 = 单轮工资 * 实际轮次;
                const 资源消耗 = 资源总消耗(建筑属性.资源需求 as Record<string, number>, 实际轮次);
                const 更新后当前值 = 当前值 + 增量;

                await Promise.all([
                    更新地区资料(ctx, 地区编号, {
                        [建筑属性.当前字段]: 更新后当前值,
                    }),
                    更新玩家资料(ctx, id, {
                        钢铁: 用户资料.钢铁 - (资源消耗.钢铁 ?? 0),
                        金属铝: 用户资料.金属铝 - (资源消耗.金属铝 ?? 0),
                        生活资料: 用户资料.生活资料 - 工资消耗,
                        生产次数: 用户资料.生产次数 - 实际轮次,
                    }),
                ]);

                const 资源消耗文本: string[] = [];
                if ((资源消耗.钢铁 ?? 0) > 0) {
                    资源消耗文本.push(`■ 钢铁消耗：${格式化(资源消耗.钢铁 ?? 0)}`);
                }
                if ((资源消耗.金属铝 ?? 0) > 0) {
                    资源消耗文本.push(`■ 金属铝消耗：${格式化(资源消耗.金属铝 ?? 0)}`);
                }

                return [
                    '====[征战文游]====',
                    `${username} 同志：`,
                    `■ 地区：${展示地区名称}（${地区编号}）`,
                    `■ 修建类型：${建筑属性.显示名}`,
                    `■ 科技需求：${格式化(建筑属性.科技需求)}`,
                    `■ 执行轮次：${格式化(实际轮次)} / ${格式化(轮次)}`,
                    `■ 本次增量：${格式化(增量)}`,
                    `■ 当前容量：${格式化(当前值)} → ${格式化(更新后当前值)} / ${格式化(上限值)}`,
                    `■ 工资消耗：${格式化(工资消耗)}`,
                    ...资源消耗文本,
                ].join('\n');
            } catch (error) {
                return (error as Error).message;
            }
        });
}
