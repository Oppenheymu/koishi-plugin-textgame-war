import dayjs from 'dayjs';
import type { Context } from 'koishi';
import { 获取运行时配置 } from '@/config';
import { TRandom } from '@/infrastructure';
import {
    列车炮炮击权限检查,
    尝试发送地区信号塔通报,
    尝试发送联军信号塔通报,
} from '@/logic';
import type { Region, RegionStrategy } from '@/types';
import { 地区解析, 更新地区战略资料, 更新地区资料, 驻扎检查 } from '@/utils';
import { 格式化距离, 计算真实距离 } from '@/地理集';

function 格式化(n: number) {
    return n.toLocaleString('zh-CN');
}

type 容量字段 = keyof Pick<
    Region,
    | '当前总基础设施'
    | '当前总公路容量'
    | '当前总机场容量'
    | '当前总港口容量'
    | '当前总居民区容量'
    | '当前总仓库容量'
>;

const 容量字段列表: 容量字段[] = [
    '当前总基础设施',
    '当前总公路容量',
    '当前总机场容量',
    '当前总港口容量',
    '当前总居民区容量',
    '当前总仓库容量',
];

const 容量显示名: Record<容量字段, string> = {
    当前总基础设施: '基础设施',
    当前总公路容量: '公路',
    当前总机场容量: '机场',
    当前总港口容量: '港口',
    当前总居民区容量: '居民区',
    当前总仓库容量: '仓库',
};

const 单门列车炮破坏基数 = 5_000_000;

export function 列车炮炮击(ctx: Context) {
    ctx.command('列车炮炮击 <目标地区:string> [列车炮数量:number]')
        .alias('列车炮轰击')
        .action(async ({ session }, 目标地区输入, 数量输入) => {
            try {
                const {
                    用户资料,
                    username,
                    当前驻扎地区,
                    地区编号,
                    展示地区名称,
                    地区战略资料,
                } = await 驻扎检查(ctx, session);

                if (当前驻扎地区 !== 地区编号) {
                    return `你当前驻扎在 ${当前驻扎地区 || '未驻扎地区'}，仅驻扎在本地区的玩家可发动列车炮炮击`;
                }

                await 列车炮炮击权限检查(ctx, session, 地区编号);

                if (!地区战略资料.是否有铁路) {
                    return '该地区暂无铁路，列车炮无法射击';
                }

                const 可用列车炮 = 地区战略资料.空闲的列车炮 ?? 0;
                if (可用列车炮 <= 0) {
                    return '该地区没有空闲的列车炮，无法炮击';
                }

                const 目标地区编号 = 目标地区输入?.trim();
                if (!目标地区编号) {
                    return '请指定炮击目标地区编号';
                }

                if (目标地区编号 === 地区编号) {
                    return '不能炮击本地区';
                }

                const 目标地区结果 = await 地区解析(ctx, 目标地区编号);

                const 射程 = 获取运行时配置().地理.列车炮最大射程公里;
                const 距离 = 计算真实距离(地区编号, 目标地区编号);
                if (距离 > 射程) {
                    return `目标地区距离 ${格式化距离(距离)}，超出列车炮最大射程 ${格式化距离(射程)}`;
                }

                let 数量: number;
                if (数量输入 == null) {
                    数量 = 可用列车炮;
                } else if (
                    !Number.isFinite(数量输入) ||
                    (数量输入 as number) <= 0 ||
                    !Number.isInteger(数量输入 as number)
                ) {
                    return '请输入有效的正整数数量';
                } else {
                    数量 = Math.min(数量输入 as number, 可用列车炮);
                }

                const 目标地区资料 = 目标地区结果.地区资料;
                const 目标战略资料 = 目标地区结果.地区战略资料;

                const 破坏结果: Record<string, number> = {};
                const 地区更新: Partial<Region> = {};

                for (const 字段 of 容量字段列表) {
                    const 当前值 = 目标地区资料[字段] ?? 0;
                    const 破坏量 = Math.floor(
                        TRandom(
                            单门列车炮破坏基数 * 0.5,
                            单门列车炮破坏基数,
                            单门列车炮破坏基数 * 1.5
                        ) * 数量
                    );
                    const 实际破坏 = Math.min(当前值, 破坏量);
                    const 剩余 = 当前值 - 实际破坏;

                    地区更新[字段] = 剩余;
                    破坏结果[容量显示名[字段]] = 实际破坏;
                }

                const 时间 = dayjs().format('YYYY-MM-DD HH:mm');

                const 战争记录 = {
                    发动者: username,
                    记录: `列车炮炮击：${数量}门列车炮轰击${目标地区结果.展示地区名称}`,
                    时间,
                };

                const 目标战略更新: Partial<RegionStrategy> = {
                    历史战争: [...(目标战略资料.历史战争 ?? []), 战争记录],
                };

                await Promise.all([
                    更新地区资料(ctx, 目标地区编号, 地区更新),
                    更新地区战略资料(ctx, 目标地区编号, 目标战略更新),
                    更新地区战略资料(ctx, 地区编号, {
                        空闲的列车炮: (地区战略资料.空闲的列车炮 ?? 0) - 数量,
                        历史战争: [
                            ...(地区战略资料.历史战争 ?? []),
                            {
                                发动者: username,
                                记录: `列车炮炮击：向${目标地区结果.展示地区名称}发射${数量}门列车炮`,
                                时间,
                            },
                        ],
                    }),
                ]);

                const 破坏文本 = Object.entries(破坏结果)
                    .filter(([, v]) => v > 0)
                    .map(([k, v]) => `${k} -${格式化(v)}`)
                    .join('、');

                const 信号塔参数 = {
                    类型: 'war' as const,
                    战争类型: '列车炮炮击' as const,
                    发起者: username,
                    发起地区名称: 展示地区名称,
                    发起地区编号: 地区编号,
                    目标地区名称: 目标地区结果.展示地区名称,
                    目标地区编号,
                    投入数量: 数量,
                    破坏概要: 破坏文本 || '无',
                };

                尝试发送地区信号塔通报(ctx, 信号塔参数);

                const 发起联军编号 = 用户资料.所在联军?.trim();
                if (发起联军编号) {
                    尝试发送联军信号塔通报(ctx, {
                        联军编号: 发起联军编号,
                        通报标题: '列车炮炮击',
                        通报内容: [
                            `${username} 发动列车炮炮击：`,
                            `■ 发起地区：${展示地区名称}（${地区编号}）`,
                            `■ 目标地区：${目标地区结果.展示地区名称}（${目标地区编号}）`,
                            `■ 投入数量：${格式化(数量)} 门`,
                            `■ 破坏效果：${破坏文本 || '无'}`,
                        ].join('\n'),
                    });
                }

                const 目标联军编号 = 目标地区结果.地区资料.控制国家?.trim();
                if (目标联军编号 && 目标联军编号 !== 发起联军编号) {
                    尝试发送联军信号塔通报(ctx, {
                        联军编号: 目标联军编号,
                        通报标题: '遭受列车炮炮击',
                        通报内容: [
                            `${展示地区名称}（${地区编号}）的列车炮正在轰击我方地区！`,
                            `■ 目标地区：${目标地区结果.展示地区名称}（${目标地区编号}）`,
                            `■ 投入数量：${格式化(数量)} 门`,
                            `■ 破坏效果：${破坏文本 || '无'}`,
                        ].join('\n'),
                    });
                }

                return [
                    '====[征战文游]====',
                    `${username} 同志：`,
                    `■ 发起地区：${展示地区名称}（${地区编号}）`,
                    `■ 目标地区：${目标地区结果.展示地区名称}（${目标地区编号}）`,
                    `■ 射击距离：${格式化距离(距离)} / ${格式化距离(射程)}`,
                    `■ 投入列车炮：${格式化(数量)} 门`,
                    `■ 破坏效果：${破坏文本 || '无'}`,
                    `■ 剩余空闲列车炮：${格式化((地区战略资料.空闲的列车炮 ?? 0) - 数量)} 门`,
                    `■ 炮击时间：${时间}`,
                ].join('\n');
            } catch (error) {
                return (error as Error).message;
            }
        });
}
