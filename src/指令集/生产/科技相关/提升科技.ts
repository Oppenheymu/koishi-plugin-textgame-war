import type { Context } from "koishi";
import { 玩家检查 } from "../../../utils/index";

export function 提升科技(ctx: Context) {
	ctx
		.command("提升科技 <生活资料:number>")
		.action(async ({ session }, 投入生活资料) => {
			try {
				const { id, username, 用户资料 } = await 玩家检查(ctx, session);

				// 格式化数字显示
				const 格式化 = (n: number) => n.toLocaleString("zh-CN");

				// 验证输入
				if (
					!投入生活资料 ||
					投入生活资料 <= 0 ||
					!Number.isInteger(投入生活资料)
				) {
					return "请输入有效的生活资料数量！\n例如：提升科技 10000";
				}

				// 检查生活资料是否足够
				if (用户资料.生活资料 < 投入生活资料) {
					return `生活资料不足！当前拥有：${格式化(
						用户资料.生活资料,
					)}，需要：${格式化(投入生活资料)}`;
				}

				// 检查是否已达到科技上限
				if (用户资料.科技等级 >= 3000) {
					return "科技已达到上限（3000级），无法继续提升！";
				}

				// 扣除生活资料
				const 减少后的生活资料 = 用户资料.生活资料 - 投入生活资料;
				let 新科技等级 = 用户资料.科技等级;
				let 科技池投入 = 用户资料.科技池投入;

				// 首先同步：检查已有的科技池投入是否足以升级
				while (新科技等级 < 3000) {
					const 升级所需 = 5000 * 新科技等级;
					if (升级所需 <= 0) {
						break;
					}
					if (科技池投入 >= 升级所需) {
						科技池投入 -= 升级所需;
						新科技等级 += 1;
					} else {
						break;
					}
				}

				// 加入新的投入
				let 增加后的科技池投入 = 科技池投入 + 投入生活资料;

				// 计算新投入后能升多少级：C(n) = 5000 × n，这是从 n 级升到 n+1 级所需容量
				let 升级次数 = 0;
				while (新科技等级 < 3000) {
					const 所需容量 = 5000 * 新科技等级;

					if (所需容量 <= 0) {
						break;
					}

					if (增加后的科技池投入 >= 所需容量) {
						增加后的科技池投入 -= 所需容量;
						新科技等级 += 1;
						升级次数 += 1;
					} else {
						break;
					}
				}

				// 计算新的科技池容量（升到下一级所需容量）
				const 新的科技池容量 = 新科技等级 < 3000 ? 5000 * 新科技等级 : 0;

				// 更新数据库
				await ctx.database.set(
					"马列玩家表",
					{
						id: id,
					},
					{
						生活资料: 减少后的生活资料,
						科技池投入: 增加后的科技池投入,
						科技等级: 新科技等级,
						科技池容量: 新的科技池容量,
					},
				);

				// 构建返回信息
				const 科技池百分比 =
					新的科技池容量 > 0
						? Math.floor((增加后的科技池投入 / 新的科技池容量) * 100)
						: 0;
				const 旧科技池百分比 =
					用户资料.科技池容量 > 0
						? Math.floor((用户资料.科技池投入 / 用户资料.科技池容量) * 100)
						: 0;
				const 百分比增长 = 科技池百分比 - 旧科技池百分比;

				let 返回信息 = `
===[征战文游]===
${username} 同志：`;

				if (升级次数 > 0) {
					返回信息 += `
成功投入科技生产
■ 科技级别：${用户资料.科技等级}→${新科技等级} (+${升级次数}级)
■ 科技池：${科技池百分比}% (${百分比增长 > 0 ? "+" : ""}${百分比增长}%)
■ 生活资料：${格式化(减少后的生活资料)} (-${格式化(投入生活资料)})`;
				} else {
					返回信息 += `
成功投入科技生产
■ 科技池：${科技池百分比}% (${百分比增长 > 0 ? "+" : ""}${百分比增长}%)
■ 生活资料：${格式化(减少后的生活资料)} (-${格式化(投入生活资料)})`;
				}

				return 返回信息.trim();
			} catch (error) {
				return (error as Error).message;
			}
		});
}
