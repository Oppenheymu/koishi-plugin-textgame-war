/** 结算所有进行中战斗的一轮 */
export async function 结算所有战斗(ctx: Context): Promise<void> {
    const 进行中战斗 = await ctx.database.get("马列战斗表", {
        状态: 战斗状态.进行中,
    });
    for (const 战斗 of 进行中战斗) {
        try {
            await 结算单场战斗(ctx, 战斗);
        } catch (error) {
            ctx.logger("战斗结算").error(
                `战斗 #${战斗.id} 结算失败：${error instanceof Error ? error.message : error}`,
            );
        }
    }
}

/** 组织度恢复（第 8 章：脱战军队每轮 +0.05，本国领土 ×2，可调） */
export async function 恢复组织度(ctx: Context): Promise<void> {
    const 驻扎军队 = await ctx.database.get("马列军队表", {
        状态: 军队状态.驻扎,
    });

    await Promise.all(
        驻扎军队.map(async (军队) => {
            let 恢复速率 = 组织度恢复速率;
            const [地区] = await ctx.database.get("马列地区表", {
                地区编号: 军队.所在地区编号,
            });
            if (地区?.控制国家 === 军队.所属联军编号) {
                恢复速率 *= 友方领土恢复倍率;
            }

            const 更新: Record<string, unknown> = {};
            if (军队.当前组织度比例 < 1) {
                更新["当前组织度比例"] = Math.min(1, 军队.当前组织度比例 + 恢复速率);
            }
            // 驻扎中重整残余兵力，HP 比例回满（永久损失已在战斗中结算）
            if (军队.当前HP比例 < 1) {
                更新["当前HP比例"] = 1;
            }
            if (Object.keys(更新).length > 0) {
                await ctx.database.set("马列军队表", { id: 军队.id }, 更新);
            }
        }),
    );
}
