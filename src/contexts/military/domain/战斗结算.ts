// ---- 本轮统计（内存跟踪，不入库）----

interface 军队本轮统计 {
    军队: Army;
    面板: 军队面板;
    本轮组织度损失: number; // 比例
    本轮HP损失: number; // 比例
    本轮造成组织度伤害: number; // 绝对值（经验累积用）
}

interface 交火结果 {
    组织度伤害: number;
    HP伤害: number;
}

/** 穿甲四档伤害系数（6.4） */
function 计算穿甲伤害系数(攻击方穿甲: number, 目标装甲: number): number {
    if (目标装甲 <= 0) return 穿甲伤害系数表.完全穿透;
    const 穿甲比 = 攻击方穿甲 / 目标装甲;
    if (穿甲比 >= 1) return 穿甲伤害系数表.完全穿透;
    if (穿甲比 >= 0.75) return 穿甲伤害系数表.大部分穿透;
    if (穿甲比 >= 0.5) return 穿甲伤害系数表.部分穿透;
    return 穿甲伤害系数表.无法穿透;
}

/**
 * 交火（6.3 破防机制 + 6.4 穿甲 + 6.5 伤害公式）
 * 随机数用 TRandom 三角分布使伤害更集中（可调：改 Math.random）
 */
function 执行交火(参数: {
    攻击点数: number;
    防御点数: number;
    穿甲伤害系数: number;
    地形地貌修正: number;
    装甲优势: boolean;
}): 交火结果 {
    const { 攻击点数, 防御点数, 穿甲伤害系数, 地形地貌修正, 装甲优势 } = 参数;

    const 被格挡部分 = Math.min(攻击点数, 防御点数);
    const 破防部分 = Math.max(0, 攻击点数 - 防御点数);
    const 期望命中次数 = 被格挡部分 * 未破防命中率 + 破防部分 * 破防命中率;
    if (期望命中次数 <= 0) return { 组织度伤害: 0, HP伤害: 0 };

    const 组织度骰子最大 = 装甲优势 ? 装甲优势骰子最大 : 组织度伤害骰子最大;
    const 单次组织度伤害 =
        TRandom(组织度伤害骰子最小, 组织度伤害骰子众数, 组织度骰子最大, false) *
        组织度伤害系数 *
        穿甲伤害系数 *
        地形地貌修正;
    const 单次HP伤害 =
        TRandom(HP伤害骰子最小, HP伤害骰子众数, HP伤害骰子最大, false) *
        HP伤害系数 *
        穿甲伤害系数 *
        地形地貌修正;

    return {
        组织度伤害: 期望命中次数 * 单次组织度伤害,
        HP伤害: 期望命中次数 * 单次HP伤害,
    };
}

/** 一方对另一方开火（6.2 攻方输出 / 守方反击 共用） */
function 执行一方输出(参数: {
    开火方: 军队本轮统计[];
    目标方: 军队本轮统计[];
    超宽惩罚: number;
    地形地貌修正: number;
    使用突破: boolean; // true=目标用突破格挡（守方反击时）；false=目标用防御
}): void {
    const { 开火方, 目标方, 超宽惩罚, 地形地貌修正, 使用突破 } = 参数;
    if (开火方.length === 0 || 目标方.length === 0) return;

    // 目标方加权平均硬度（按士兵数量加权）
    const 目标方总兵力 = 目标方.reduce((和, t) => 和 + t.军队.士兵数量, 0);
    const 目标硬度 =
        目标方总兵力 > 0
            ? 目标方.reduce((和, t) => 和 + t.面板.硬度 * t.军队.士兵数量, 0) / 目标方总兵力
            : 0;

    // TODO(第二阶段): 空军支援——有制空权方攻击修正 +X%，侦察机提供情报（挂载点）

    for (const 攻击方 of 开火方) {
        const 面板 = 攻击方.面板;
        if (面板.软攻 <= 0 && 面板.硬攻 <= 0) continue;

        const 经验修正 = 计算经验修正(攻击方.军队.经验值, 经验修正上限, 经验修正除数);
        const HP衰减 = 计算HP衰减系数(攻击方.军队.当前HP比例);
        const 综合修正 = 地形地貌修正 * (1 + 超宽惩罚) * HP衰减 * 经验修正;

        const 有效软攻 = 面板.软攻 * (1 - 目标硬度) * 综合修正;
        const 有效硬攻 = 面板.硬攻 * 目标硬度 * 综合修正;
        const 攻击点数 = Math.round((有效软攻 + 有效硬攻) / 攻击点数除数);
        if (攻击点数 <= 0) continue;

        // 随机选取一支目标军队为主目标（目标方非空已在上文保证）
        const 主目标 = 目标方[Math.floor(Math.random() * 目标方.length)]!;
        const 目标面板 = 主目标.面板;

        // 防守方用防御，进攻方用突破，不互通；格挡点数同样受 HP 衰减
        const 目标格挡属性 = 使用突破 ? 目标面板.突破 : 目标面板.防御;
        const 防御点数 = Math.round(
            (目标格挡属性 * 计算HP衰减系数(主目标.军队.当前HP比例)) / 攻击点数除数,
        );

        const 穿甲系数 = 计算穿甲伤害系数(面板.穿甲, 目标面板.装甲);
        // 装甲优势：攻击方为装甲单位且目标穿不动我（6.4）
        const 装甲优势 = 面板.硬度 >= 装甲优势硬度阈值 && 目标面板.穿甲 < 面板.装甲;

        const { 组织度伤害, HP伤害 } = 执行交火({
            攻击点数,
            防御点数,
            穿甲伤害系数: 穿甲系数,
            地形地貌修正,
            装甲优势,
        });

        // 6.5 伤害入账（比例 = 伤害 ÷ 上限，上限为 0 时视为已崩溃不再扣）
        if (目标面板.组织度 > 0) {
            const 组织度比例损失 = 组织度伤害 / 目标面板.组织度;
            主目标.军队.当前组织度比例 = Math.max(0, 主目标.军队.当前组织度比例 - 组织度比例损失);
            主目标.本轮组织度损失 += 组织度比例损失;
        }
        if (目标面板.HP > 0) {
            const HP比例损失 = HP伤害 / 目标面板.HP;
            主目标.军队.当前HP比例 = Math.max(0, 主目标.军队.当前HP比例 - HP比例损失);
            主目标.本轮HP损失 += HP比例损失;
        }
        攻击方.本轮造成组织度伤害 += 组织度伤害;
    }
}

/** 撤退（6.7）：返回 "撤退" | "歼灭" */
async function 执行撤退(
    ctx: Context,
    军队: Army,
    面板: 军队面板,
    战斗地区编号: string,
): Promise<{ 结果: "撤退" | "歼灭"; 目的地?: string }> {
    const 邻居编号列表 = await 获取相邻地区(ctx, 战斗地区编号);
    const 相邻地区列表: Region[] = [];
    for (const { 地区编号 } of 邻居编号列表) {
        const [地区] = await ctx.database.get("马列地区表", { 地区编号 });
        if (地区) 相邻地区列表.push(地区);
    }

    const 目的地 = 选择撤退目的地({
        当前地区编号: 战斗地区编号,
        所属联军编号: 军队.所属联军编号,
        相邻地区列表,
    });

    // 无路可退（四邻皆敌/海洋）→ 歼灭，装备与士兵全损
    if (!目的地) {
        await ctx.database.remove("马列军队表", { id: 军队.id });
        return { 结果: "歼灭" };
    }

    const [目的地区] = await ctx.database.get("马列地区表", {
        地区编号: 目的地,
    });
    const [战斗地区] = await ctx.database.get("马列地区表", {
        地区编号: 战斗地区编号,
    });
    const [目的地貌] = await ctx.database.get("马列地区地形表", {
        地区编号: 目的地,
    });

    const 行军毫秒 =
        目的地区 && 战斗地区 && 目的地貌
            ? 计算行军毫秒数({
                  基础速度: Math.max(1, 面板.速度),
                  出发地区编号: 战斗地区编号,
                  目标地区编号: 目的地,
                  出发地形: 战斗地区.地区地形,
                  目标地形: 目的地区.地区地形,
                  目标地貌: 目的地貌,
              })
            : 5 * 60 * 1000;

    await ctx.database.set(
        "马列军队表",
        { id: 军队.id },
        {
            状态: 军队状态.撤退中,
            目标地区编号: 目的地,
            预计到达时间: new Date(Date.now() + 行军毫秒).toISOString(),
            当前战斗编号: null,
            战斗阵营: null,
            当前组织度比例: 0,
        },
    );
    return { 结果: "撤退", 目的地 };
}

/** 战报中的一行军队状态（模糊分级，可调为精确数值） */
function 格式化军队战况(统计: 军队本轮统计): string {
    const { 军队 } = 统计;
    if (战报显示精确数值) {
        return `■ ${军队.名称}：组织度 ${(军队.当前组织度比例 * 100).toFixed(0)}% / HP ${(军队.当前HP比例 * 100).toFixed(0)}%`;
    }
    return `■ ${军队.名称}：${组织度分级(军队.当前组织度比例)} / ${HP分级(军队.当前HP比例)}`;
}

/** 结算单场战斗的一轮（6.2 完整流程） */
async function 结算单场战斗(ctx: Context, 战斗: Battle): Promise<void> {
    const 事件列表: string[] = [];
    战斗.回合数 += 1;

    const 参战军队 = await ctx.database.get("马列军队表", {
        当前战斗编号: 战斗.id,
    });
    const 攻方军队 = 参战军队.filter((a) => a.战斗阵营 === 战斗阵营.进攻);
    const 守方军队 = 参战军队.filter((a) => a.战斗阵营 === 战斗阵营.防守);

    // 一方已空 → 直接结束
    if (攻方军队.length === 0 || 守方军队.length === 0) {
        await 结束战斗(ctx, 战斗, 攻方军队, 守方军队, 事件列表);
        return;
    }

    const [地区] = await ctx.database.get("马列地区表", {
        地区编号: 战斗.地区编号,
    });
    const [地貌] = await ctx.database.get("马列地区地形表", {
        地区编号: 战斗.地区编号,
    });
    if (!地区 || !地貌) {
        throw new Error(`战斗 #${战斗.id} 地区数据缺失`);
    }

    // ---- 入场宽度匹配（6.2：按番号顺序入场，宽度满则后续排队预备队）----
    const 战场宽度 = 计算战场宽度(地区.地区地形, 地貌);
    const 面板缓存 = new Map<number, 军队面板>();
    const 取面板 = (军队: Army): 军队面板 => {
        let 面板 = 面板缓存.get(军队.id);
        if (!面板) {
            面板 = 聚合军队面板(军队);
            面板缓存.set(军队.id, 面板);
        }
        return 面板;
    };

    const 入场选择 = (军队列表: Army[]): { 上场: Army[]; 上场总宽度: number } => {
        const 排序 = [...军队列表].sort((a, b) => a.番号 - b.番号);
        const 上场: Army[] = [];
        let 上场总宽度 = 0;
        for (const 军队 of 排序) {
            if (上场.length > 0 && 上场总宽度 >= 战场宽度) break;
            上场.push(军队);
            上场总宽度 += 取面板(军队).宽度;
        }
        return { 上场, 上场总宽度 };
    };

    const 攻方入场 = 入场选择(攻方军队);
    const 守方入场 = 入场选择(守方军队);
    const 攻方超宽惩罚 = 计算超宽惩罚(攻方入场.上场总宽度, 战场宽度);
    const 守方超宽惩罚 = 计算超宽惩罚(守方入场.上场总宽度, 战场宽度);

    const 建统计 = (军队: Army): 军队本轮统计 => ({
        军队,
        面板: 取面板(军队),
        本轮组织度损失: 0,
        本轮HP损失: 0,
        本轮造成组织度伤害: 0,
    });
    const 攻方统计 = 攻方入场.上场.map(建统计);
    const 守方统计 = 守方入场.上场.map(建统计);

    const 攻击地形地貌修正 = 计算攻击地形地貌修正(地区.地区地形, 地貌);

    // ---- 攻方输出（吃地形惩罚）----
    执行一方输出({
        开火方: 攻方统计,
        目标方: 守方统计,
        超宽惩罚: 攻方超宽惩罚,
        地形地貌修正: 攻击地形地貌修正,
        使用突破: false,
    });

    // ---- 守方反击（防守方熟悉地形，不吃地形惩罚，可调）----
    执行一方输出({
        开火方: 守方统计,
        目标方: 攻方统计,
        超宽惩罚: 守方超宽惩罚,
        地形地貌修正: 1,
        使用突破: true,
    });

    // ---- 死守惩罚（6.2：组织度锁 0，每轮额外吃 HP 伤害 ×1.5）----
    for (const 统计 of [...攻方统计, ...守方统计]) {
        if (
            统计.军队.当前命令 === 军队命令.死守 &&
            统计.军队.当前组织度比例 <= 0 &&
            统计.本轮HP损失 > 0
        ) {
            const 额外损失 = 统计.本轮HP损失 * (死守HP伤害倍率 - 1);
            统计.军队.当前HP比例 = Math.max(0, 统计.军队.当前HP比例 - 额外损失);
            统计.本轮HP损失 += 额外损失;
        }
    }

    // ---- 歼灭判定（HP 归零 / 兵力打光）----
    const 存活判定 = async (
        统计列表: 军队本轮统计[],
        阵营名称: string,
    ): Promise<军队本轮统计[]> => {
        const 存活: 军队本轮统计[] = [];
        for (const 统计 of 统计列表) {
            if (统计.军队.当前HP比例 <= 0 || 统计.军队.士兵数量 <= 0) {
                await ctx.database.remove("马列军队表", { id: 统计.军队.id });
                事件列表.push(`💥 ${统计.军队.名称}（${阵营名称}）被歼灭`);
            } else {
                存活.push(统计);
            }
        }
        return 存活;
    };

    let 攻方存活 = await 存活判定(攻方统计, "进攻方");
    let 守方存活 = await 存活判定(守方统计, "防守方");

    // ---- 溃退判定（6.2：组织度归零且非死守 → 强制撤退）----
    const 溃退判定 = async (
        统计列表: 军队本轮统计[],
        阵营名称: string,
    ): Promise<军队本轮统计[]> => {
        const 留下: 军队本轮统计[] = [];
        for (const 统计 of 统计列表) {
            const 溃退 = 统计.军队.当前组织度比例 <= 0 && 统计.军队.当前命令 !== 军队命令.死守;
            const 听令撤退 = 统计.军队.当前命令 === 军队命令.撤退;
            if (!溃退 && !听令撤退) {
                留下.push(统计);
                continue;
            }
            const { 结果, 目的地 } = await 执行撤退(ctx, 统计.军队, 统计.面板, 战斗.地区编号);
            if (结果 === "歼灭") {
                事件列表.push(`💥 ${统计.军队.名称}（${阵营名称}）无路可退，被歼灭`);
            } else {
                事件列表.push(
                    `🏳️ ${统计.军队.名称}（${阵营名称}）${溃退 ? "溃退" : "撤退"}至 ${目的地}`,
                );
            }
        }
        return 留下;
    };

    攻方存活 = await 溃退判定(攻方存活, "进攻方");
    守方存活 = await 溃退判定(守方存活, "防守方");

    // ---- 实际损失结算（6.6：本轮HP损失 × 70% 转为装备与士兵永久损失）----
    const 结算实际损失 = async (统计列表: 军队本轮统计[]): Promise<void> => {
        for (const 统计 of 统计列表) {
            const 损失率 = Math.min(1, 统计.本轮HP损失 * HP损失转化率);
            const 更新: Record<string, unknown> = {
                当前组织度比例: 统计.军队.当前组织度比例,
                当前HP比例: 统计.军队.当前HP比例,
                经验值: 统计.军队.经验值 + 统计.本轮造成组织度伤害 * 经验累积系数,
            };
            if (损失率 > 0) {
                更新["士兵数量"] = Math.floor(统计.军队.士兵数量 * (1 - 损失率));
                for (const 键 of 装备数量列名单) {
                    更新[键] = Math.floor(((统计.军队[键] as number) ?? 0) * (1 - 损失率));
                }
            }
            await ctx.database.set("马列军队表", { id: 统计.军队.id }, 更新);
        }
    };
    await 结算实际损失(攻方存活);
    await 结算实际损失(守方存活);

    // 预备队（未上场）同步经验与状态写回
    const 上场编号集合 = new Set([...攻方统计, ...守方统计].map((t) => t.军队.id));
    const 预备队 = 参战军队.filter((a) => !上场编号集合.has(a.id));
    await Promise.all(
        预备队.map((军队) =>
            ctx.database.set(
                "马列军队表",
                { id: 军队.id },
                {
                    当前组织度比例: 军队.当前组织度比例,
                    当前HP比例: 军队.当前HP比例,
                },
            ),
        ),
    );

    // ---- 战斗结束判定 ----
    if (攻方存活.length === 0 || 守方存活.length === 0) {
        await 结束战斗(ctx, 战斗, 攻方存活, 守方存活, 事件列表);
        return;
    }

    // ---- 未结束：写回回合数并推送战报 ----
    await ctx.database.set(
        "马列战斗表",
        { id: 战斗.id },
        {
            回合数: 战斗.回合数,
        },
    );

    await 推送战报(ctx, 战斗, 攻方存活, 守方存活, 事件列表, false);
}

/** 推送战报（6.9：地区群简报 + 双方首都群大战报） */
async function 推送战报(
    ctx: Context,
    战斗: Battle,
    攻方: 军队本轮统计[],
    守方: 军队本轮统计[],
    事件列表: string[],
    是否终局: boolean,
): Promise<void> {
    const 名称缓存 = await 加载联军名称缓存(ctx, [战斗.进攻方联军编号, 战斗.防守方联军编号]);
    const 攻方名称 = 名称缓存.get(战斗.进攻方联军编号);
    const 守方名称 = 名称缓存.get(战斗.防守方联军编号);

    const 文本行: string[] = [
        `【战报】${战斗.地区编号}地区 第${战斗.回合数}回合${是否终局 ? "（终局）" : ""}`,
        `进攻方：${攻方名称} | 防守方：${守方名称}`,
        ...攻方.map(格式化军队战况),
        ...守方.map(格式化军队战况),
        ...事件列表,
    ];
    const 文本 = 文本行.join("\n");

    // 战斗发生地区绑定群聊（每轮简报）
    await 向地区绑定群推送(ctx, 战斗.地区编号, 文本);

    // 双方联军首都绑定群聊（大战报）
    const 联军列表 = await ctx.database.get("马列联军表", {
        联军编号: { $in: [战斗.进攻方联军编号, 战斗.防守方联军编号] },
    });
    for (const 联军 of 联军列表) {
        if (联军.联军首都 && 联军.联军首都 !== 战斗.地区编号) {
            await 向地区绑定群推送(ctx, 联军.联军首都, 文本);
        }
    }
}

/** 结束战斗：写结果、胜方驻军、地区易主、推送终局战报 */
async function 结束战斗(
    ctx: Context,
    战斗: Battle,
    攻方剩余: (Army | 军队本轮统计)[],
    守方剩余: (Army | 军队本轮统计)[],
    事件列表: string[],
): Promise<void> {
    const 取军队 = (item: Army | 军队本轮统计): Army => ("军队" in item ? item.军队 : item);

    let 结果: string;
    if (攻方剩余.length > 0 && 守方剩余.length === 0) {
        结果 = "进攻方胜";
    } else if (守方剩余.length > 0 && 攻方剩余.length === 0) {
        结果 = "防守方胜";
    } else {
        结果 = "双方同归于尽";
    }

    await ctx.database.set(
        "马列战斗表",
        { id: 战斗.id },
        {
            回合数: 战斗.回合数,
            状态: 战斗状态.已结束,
            结束时间: new Date().toISOString(),
            结果,
        },
    );

    // 双方所有剩余参战军队（含预备队）统一脱战转驻扎、恢复满 HP（残余兵力重整，可调）
    // 败方残余如滞留敌区，可由指挥官下轮自行撤离（第一阶段简化处理）
    const 剩余参战军队 = await ctx.database.get("马列军队表", {
        当前战斗编号: 战斗.id,
    });
    await Promise.all(
        剩余参战军队.map((军队) =>
            ctx.database.set(
                "马列军队表",
                { id: 军队.id },
                {
                    状态: 军队状态.驻扎,
                    所在地区编号: 战斗.地区编号,
                    目标地区编号: null,
                    预计到达时间: null,
                    当前战斗编号: null,
                    战斗阵营: null,
                    当前HP比例: 1,
                    当前命令: 军队命令.正常,
                    命令下达者军衔: 0,
                },
            ),
        ),
    );

    // 进攻方胜 → 地区易主
    if (结果 === "进攻方胜") {
        await ctx.database.set(
            "马列地区表",
            { 地区编号: 战斗.地区编号 },
            { 控制国家: 战斗.进攻方联军编号 },
        );
        事件列表.push(`🏴 ${战斗.地区编号}地区已易主`);
    }

    事件列表.push(`⚔️ 战斗结束：${结果}`);

    // 终局战报（剩余军队可能为 0，容错处理）
    const 攻方统计 = 攻方剩余.map((item) => {
        const 军队 = 取军队(item);
        return {
            军队,
            面板: 聚合军队面板(军队),
            本轮组织度损失: 0,
            本轮HP损失: 0,
            本轮造成组织度伤害: 0,
        };
    });
    const 守方统计 = 守方剩余.map((item) => {
        const 军队 = 取军队(item);
        return {
            军队,
            面板: 聚合军队面板(军队),
            本轮组织度损失: 0,
            本轮HP损失: 0,
            本轮造成组织度伤害: 0,
        };
    });
    await 推送战报(ctx, 战斗, 攻方统计, 守方统计, 事件列表, true);
}

