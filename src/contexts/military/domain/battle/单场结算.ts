/** 军队表 27 个装备数量列（实际损失结算用） */
const 装备数量列名单 = [
    "步兵装备",
    "卡车",
    "两栖坦克",
    "轻型坦克",
    "中型坦克",
    "重型坦克",
    "现代坦克",
    "装甲运兵车",
    "两栖装甲运兵车",
    "坦克歼击车",
    "自行防空车",
    "野战炮",
    "火炮",
    "火箭炮",
    "列车炮",
    "侦察机",
    "战斗机",
    "预警机",
    "战术轰炸机",
    "战略轰炸机",
    "隐形轰炸机",
    "大型运输机",
    "小型运输机",
    "火箭弹",
    "防空弹药",
    "轻型航弹",
    "重型航弹",
] as const;

/** 结算单场战斗的一轮（6.2 完整流程） */
export async function 结算单场战斗(ctx: Context, 战斗: Battle): Promise<void> {
    const 事件列表: string[] = [];
    战斗.回合数 += 1;

    const 参战军队 = await ctx.database.get("征战军队表", {
        当前战斗编号: 战斗.id,
    });
    const 攻方军队 = 参战军队.filter((a) => a.战斗阵营 === 战斗阵营.进攻);
    const 守方军队 = 参战军队.filter((a) => a.战斗阵营 === 战斗阵营.防守);

    // 一方已空 → 直接结束
    if (攻方军队.length === 0 || 守方军队.length === 0) {
        await 结束战斗(ctx, 战斗, 攻方军队, 守方军队, 事件列表);
        return;
    }

    const [地区] = await ctx.database.get("征战地区表", {
        地区编号: 战斗.地区编号,
    });
    const [地貌] = await ctx.database.get("征战地区地形表", {
        地区编号: 战斗.地区编号,
    });
    if (!地区 || !地貌) {
        throw new Error(`战斗 #${战斗.id} 地区数据缺失`);
    }

    // ---- 入场宽度匹配（6.2：按番号顺序入场，宽度满则后续排队预备队）----
    const 战场宽度 = 计算战场宽度(地区.地区地形, 地貌);
    const 面板缓存 = new Map<number, 军队面板>();
    const 取面板 = (军队: Army): 军队面板 => {
        let 面板 = 面板缓存.get(军队.id);
        if (!面板) {
            面板 = 聚合军队面板(军队);
            面板缓存.set(军队.id, 面板);
        }
        return 面板;
    };

    const 入场选择 = (军队列表: Army[]): { 上场: Army[]; 上场总宽度: number } => {
        const 排序 = [...军队列表].sort((a, b) => a.番号 - b.番号);
        const 上场: Army[] = [];
        let 上场总宽度 = 0;
        for (const 军队 of 排序) {
            if (上场.length > 0 && 上场总宽度 >= 战场宽度) break;
            上场.push(军队);
            上场总宽度 += 取面板(军队).宽度;
        }
        return { 上场, 上场总宽度 };
    };

    const 攻方入场 = 入场选择(攻方军队);
    const 守方入场 = 入场选择(守方军队);
    const 攻方超宽惩罚 = 计算超宽惩罚(攻方入场.上场总宽度, 战场宽度);
    const 守方超宽惩罚 = 计算超宽惩罚(守方入场.上场总宽度, 战场宽度);

    const 建统计 = (军队: Army): 军队本轮统计 => ({
        军队,
        面板: 取面板(军队),
        本轮组织度损失: 0,
        本轮HP损失: 0,
        本轮造成组织度伤害: 0,
    });
    const 攻方统计 = 攻方入场.上场.map(建统计);
    const 守方统计 = 守方入场.上场.map(建统计);

    const 攻击地形地貌修正 = 计算攻击地形地貌修正(地区.地区地形, 地貌);

    // ---- 攻方输出（吃地形惩罚）----
    执行一方输出({
        开火方: 攻方统计,
        目标方: 守方统计,
        超宽惩罚: 攻方超宽惩罚,
        地形地貌修正: 攻击地形地貌修正,
        使用突破: false,
    });

    // ---- 守方反击（防守方熟悉地形，不吃地形惩罚，可调）----
    执行一方输出({
        开火方: 守方统计,
        目标方: 攻方统计,
        超宽惩罚: 守方超宽惩罚,
        地形地貌修正: 1,
        使用突破: true,
    });

    // ---- 死守惩罚（6.2：组织度锁 0，每轮额外吃 HP 伤害 ×1.5）----
    for (const 统计 of [...攻方统计, ...守方统计]) {
        if (
            统计.军队.当前命令 === 军队命令.死守 &&
            统计.军队.当前组织度比例 <= 0 &&
            统计.本轮HP损失 > 0
        ) {
            const 额外损失 = 统计.本轮HP损失 * (死守HP伤害倍率 - 1);
            统计.军队.当前HP比例 = Math.max(0, 统计.军队.当前HP比例 - 额外损失);
            统计.本轮HP损失 += 额外损失;
        }
    }

    // ---- 歼灭判定（HP 归零 / 兵力打光）----
    const 存活判定 = async (
        统计列表: 军队本轮统计[],
        阵营名称: string,
    ): Promise<军队本轮统计[]> => {
        const 存活: 军队本轮统计[] = [];
        for (const 统计 of 统计列表) {
            if (统计.军队.当前HP比例 <= 0 || 统计.军队.士兵数量 <= 0) {
                await ctx.database.remove("征战军队表", { id: 统计.军队.id });
                事件列表.push(`💥 ${统计.军队.名称}（${阵营名称}）被歼灭`);
            } else {
                存活.push(统计);
            }
        }
        return 存活;
    };

    let 攻方存活 = await 存活判定(攻方统计, "进攻方");
    let 守方存活 = await 存活判定(守方统计, "防守方");

    // ---- 溃退判定（6.2：组织度归零且非死守 → 强制撤退）----
    const 溃退判定 = async (
        统计列表: 军队本轮统计[],
        阵营名称: string,
    ): Promise<军队本轮统计[]> => {
        const 留下: 军队本轮统计[] = [];
        for (const 统计 of 统计列表) {
            const 溃退 = 统计.军队.当前组织度比例 <= 0 && 统计.军队.当前命令 !== 军队命令.死守;
            const 听令撤退 = 统计.军队.当前命令 === 军队命令.撤退;
            if (!溃退 && !听令撤退) {
                留下.push(统计);
                continue;
            }
            const { 结果, 目的地 } = await 执行撤退(ctx, 统计.军队, 统计.面板, 战斗.地区编号);
            if (结果 === "歼灭") {
                事件列表.push(`💥 ${统计.军队.名称}（${阵营名称}）无路可退，被歼灭`);
            } else {
                事件列表.push(
                    `🏳️ ${统计.军队.名称}（${阵营名称}）${溃退 ? "溃退" : "撤退"}至 ${目的地}`,
                );
            }
        }
        return 留下;
    };

    攻方存活 = await 溃退判定(攻方存活, "进攻方");
    守方存活 = await 溃退判定(守方存活, "防守方");

    // ---- 实际损失结算（6.6：本轮HP损失 × 70% 转为装备与士兵永久损失）----
    const 结算实际损失 = async (
        统计列表: 军队本轮统计[],
        阵营名称: string,
    ): Promise<军队本轮统计[]> => {
        const 仍存活: 军队本轮统计[] = [];
        for (const 统计 of 统计列表) {
            const 损失率 = Math.min(1, 统计.本轮HP损失 * HP损失转化率);
            const 剩余士兵 =
                损失率 > 0 ? Math.floor(统计.军队.士兵数量 * (1 - 损失率)) : 统计.军队.士兵数量;

            // 战损折算后士兵归零 → 编制打光，就地歼灭（修复 floor 取整后的"僵尸军队"）
            if (剩余士兵 <= 0) {
                await ctx.database.remove("征战军队表", { id: 统计.军队.id });
                事件列表.push(`💥 ${统计.军队.名称}（${阵营名称}）残部打光，编制撤销`);
                continue;
            }

            const 更新: Record<string, unknown> = {
                当前组织度比例: 统计.军队.当前组织度比例,
                当前HP比例: 统计.军队.当前HP比例,
                经验值: 统计.军队.经验值 + 统计.本轮造成组织度伤害 * 经验累积系数,
                士兵数量: 剩余士兵,
            };
            if (损失率 > 0) {
                for (const 键 of 装备数量列名单) {
                    更新[键] = Math.floor(((统计.军队[键] as number) ?? 0) * (1 - 损失率));
                }
            }
            await ctx.database.set("征战军队表", { id: 统计.军队.id }, 更新);
            仍存活.push(统计);
        }
        return 仍存活;
    };
    攻方存活 = await 结算实际损失(攻方存活, "进攻方");
    守方存活 = await 结算实际损失(守方存活, "防守方");

    // 预备队（未上场）本轮无战损无经验，状态不变，无需写库

    // ---- 战斗结束判定 ----
    if (攻方存活.length === 0 || 守方存活.length === 0) {
        await 结束战斗(ctx, 战斗, 攻方存活, 守方存活, 事件列表);
        return;
    }

    // ---- 未结束：写回回合数并推送战报 ----
    await ctx.database.set(
        "征战战斗表",
        { id: 战斗.id },
        {
            回合数: 战斗.回合数,
        },
    );

    await 推送战报(ctx, 战斗, 攻方存活, 守方存活, 事件列表, false);
}
