// 单场战斗的一轮结算（6.2 完整流程编排，详见 军事系统.prompt.md 第 6 章）
import type { Context } from "koishi";
import type { Battle } from "#ctx/military/domain/types/数据类型";

import { 战斗阵营 } from "#ctx/military/domain/types/枚举";

import { 计算战场宽度, 计算攻击地形地貌修正, 计算超宽惩罚 } from "#ctx/military/domain/战场宽度";

import { 执行一方输出 } from "./伤害计算.js";
import { 创建面板缓存, 建立统计列表, 选择入场军队 } from "./入场.js";
import { 包装预备队统计, 应用死守惩罚, 执行存活判定, 执行溃退判定, 结算实际损失 } from "./判定.js";
import { 推送战报 } from "./战报生成.js";
import { 结束战斗 } from "./战斗结束.js";

/** 结算单场战斗的一轮（6.2 完整流程） */
export async function 结算单场战斗(ctx: Context, 战斗: Battle): Promise<void> {
    const 事件列表: string[] = [];
    战斗.回合数 += 1;

    const 参战军队 = await ctx.database.get("征战军队表", {
        当前战斗编号: 战斗.id,
    });
    const 攻方军队 = 参战军队.filter((a) => a.战斗阵营 === 战斗阵营.进攻);
    const 守方军队 = 参战军队.filter((a) => a.战斗阵营 === 战斗阵营.防守);

    // 一方已空 → 直接结束
    if (攻方军队.length === 0 || 守方军队.length === 0) {
        await 结束战斗(ctx, 战斗, 攻方军队, 守方军队, 事件列表);
        return;
    }

    const [地区] = await ctx.database.get("征战地区表", {
        地区编号: 战斗.地区编号,
    });
    const [地貌] = await ctx.database.get("征战地区地形表", {
        地区编号: 战斗.地区编号,
    });
    if (!地区 || !地貌) {
        throw new Error(`战斗 #${战斗.id} 地区数据缺失`);
    }

    // ---- 入场宽度匹配（6.2）----
    const 战场宽度 = 计算战场宽度(地区.地区地形, 地貌);
    const 取面板 = 创建面板缓存();

    const 攻方入场 = 选择入场军队(攻方军队, 战场宽度, 取面板);
    const 守方入场 = 选择入场军队(守方军队, 战场宽度, 取面板);
    const 攻方超宽惩罚 = 计算超宽惩罚(攻方入场.上场总宽度, 战场宽度);
    const 守方超宽惩罚 = 计算超宽惩罚(守方入场.上场总宽度, 战场宽度);

    const 攻方统计 = 建立统计列表(攻方入场.上场, 取面板);
    const 守方统计 = 建立统计列表(守方入场.上场, 取面板);

    // ---- 攻方输出（吃地形惩罚）----
    执行一方输出({
        开火方: 攻方统计,
        目标方: 守方统计,
        超宽惩罚: 攻方超宽惩罚,
        地形地貌修正: 计算攻击地形地貌修正(地区.地区地形, 地貌),
        使用突破: false,
    });

    // ---- 守方反击（防守方熟悉地形，不吃地形惩罚，可调）----
    执行一方输出({
        开火方: 守方统计,
        目标方: 攻方统计,
        超宽惩罚: 守方超宽惩罚,
        地形地貌修正: 1,
        使用突破: true,
    });

    // ---- 死守惩罚 + 歼灭/溃退判定 + 实际损失结算 ----
    应用死守惩罚([...攻方统计, ...守方统计]);

    let 攻方存活 = await 执行存活判定(ctx, 攻方统计, "进攻方", 事件列表);
    let 守方存活 = await 执行存活判定(ctx, 守方统计, "防守方", 事件列表);

    攻方存活 = await 执行溃退判定(ctx, 攻方存活, "进攻方", 战斗.地区编号, 事件列表);
    守方存活 = await 执行溃退判定(ctx, 守方存活, "防守方", 战斗.地区编号, 事件列表);

    攻方存活 = await 结算实际损失(ctx, 攻方存活, "进攻方", 事件列表);
    守方存活 = await 结算实际损失(ctx, 守方存活, "防守方", 事件列表);

    // 预备队（未上场）本轮无战损无经验，状态不变，无需写库
    const 上场编号集合 = new Set([...攻方统计, ...守方统计].map((t) => t.军队.id));
    const 攻方预备队统计 = 包装预备队统计(
        攻方军队.filter((a) => !上场编号集合.has(a.id)),
        取面板,
    );
    const 守方预备队统计 = 包装预备队统计(
        守方军队.filter((a) => !上场编号集合.has(a.id)),
        取面板,
    );

    // ---- 战斗结束判定（任一方上场部队与预备队全灭/全撤才算结束，预备队下轮接战）----
    const 攻方余部 = [...攻方存活, ...攻方预备队统计];
    const 守方余部 = [...守方存活, ...守方预备队统计];
    if (攻方余部.length === 0 || 守方余部.length === 0) {
        await 结束战斗(ctx, 战斗, 攻方余部, 守方余部, 事件列表);
        return;
    }

    // ---- 未结束：写回回合数并推送战报 ----
    await ctx.database.set(
        "征战战斗表",
        { id: 战斗.id },
        {
            回合数: 战斗.回合数,
        },
    );

    await 推送战报(ctx, 战斗, 攻方余部, 守方余部, 事件列表, false);
}
