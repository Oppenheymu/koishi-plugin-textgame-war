// 伤害计算（6.2 攻方输出 / 守方反击 共用，详见 军事系统.prompt.md 第 6 章）
import {
    攻击点数除数,
    经验修正上限,
    经验修正除数,
    装甲优势硬度阈值,
} from "#ctx/military/domain/types/常量";

import { 计算HP衰减系数, 计算经验修正 } from "#ctx/military/domain/属性聚合";

import type { 军队本轮统计 } from "./本轮统计.js";
import { 执行交火, 计算穿甲伤害系数 } from "./骰子结算.js";

/** 一方对另一方开火（6.2 攻方输出 / 守方反击 共用） */
export function 执行一方输出(参数: {
    开火方: 军队本轮统计[];
    目标方: 军队本轮统计[];
    超宽惩罚: number;
    地形地貌修正: number;
    使用突破: boolean; // true=目标用突破格挡（守方反击时）；false=目标用防御
}): void {
    const { 开火方, 目标方, 超宽惩罚, 地形地貌修正, 使用突破 } = 参数;
    if (开火方.length === 0 || 目标方.length === 0) return;

    // 目标方加权平均硬度（按士兵数量加权）
    const 目标方总兵力 = 目标方.reduce((和, t) => 和 + t.军队.士兵数量, 0);
    const 目标硬度 =
        目标方总兵力 > 0
            ? 目标方.reduce((和, t) => 和 + t.面板.硬度 * t.军队.士兵数量, 0) / 目标方总兵力
            : 0;

    // TODO(第二阶段): 空军支援——有制空权方攻击修正 +X%，侦察机提供情报（挂载点）

    for (const 攻击方 of 开火方) {
        const 面板 = 攻击方.面板;
        if (面板.软攻 <= 0 && 面板.硬攻 <= 0) continue;

        const 经验修正 = 计算经验修正(攻击方.军队.经验值, 经验修正上限, 经验修正除数);
        const HP衰减 = 计算HP衰减系数(攻击方.军队.当前HP比例);
        const 综合修正 = 地形地貌修正 * (1 + 超宽惩罚) * HP衰减 * 经验修正;

        const 有效软攻 = 面板.软攻 * (1 - 目标硬度) * 综合修正;
        const 有效硬攻 = 面板.硬攻 * 目标硬度 * 综合修正;
        const 攻击点数 = Math.round((有效软攻 + 有效硬攻) / 攻击点数除数);
        if (攻击点数 <= 0) continue;

        // 随机选取一支目标军队为主目标（目标方非空已在上文保证）
        const 主目标 = 目标方[Math.floor(Math.random() * 目标方.length)]!;
        const 目标面板 = 主目标.面板;

        // 防守方用防御，进攻方用突破，不互通；格挡点数同样受 HP 衰减
        const 目标格挡属性 = 使用突破 ? 目标面板.突破 : 目标面板.防御;
        const 防御点数 = Math.round(
            (目标格挡属性 * 计算HP衰减系数(主目标.军队.当前HP比例)) / 攻击点数除数,
        );

        const 穿甲系数 = 计算穿甲伤害系数(面板.穿甲, 目标面板.装甲);
        // 装甲优势：攻击方为装甲单位且目标穿不动我（6.4）
        const 装甲优势 = 面板.硬度 >= 装甲优势硬度阈值 && 目标面板.穿甲 < 面板.装甲;

        const { 组织度伤害, HP伤害 } = 执行交火({
            攻击点数,
            防御点数,
            穿甲伤害系数: 穿甲系数,
            地形地貌修正,
            装甲优势,
        });

        // 6.5 伤害入账（比例 = 伤害 ÷ 上限，上限为 0 时视为已崩溃不再扣）
        if (目标面板.组织度 > 0) {
            const 组织度比例损失 = 组织度伤害 / 目标面板.组织度;
            主目标.军队.当前组织度比例 = Math.max(0, 主目标.军队.当前组织度比例 - 组织度比例损失);
            主目标.本轮组织度损失 += 组织度比例损失;
        }
        if (目标面板.HP > 0) {
            const HP比例损失 = HP伤害 / 目标面板.HP;
            主目标.军队.当前HP比例 = Math.max(0, 主目标.军队.当前HP比例 - HP比例损失);
            主目标.本轮HP损失 += HP比例损失;
        }
        攻击方.本轮造成组织度伤害 += 组织度伤害;
    }
}
