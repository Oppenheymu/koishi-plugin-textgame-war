// 军队属性聚合（纯函数，不落库，详见 军事系统.prompt.md 第 4 章）
// 输入：军队装备数量 + 士兵数量；输出：军队面板
import type { Army, 军队面板, 陆军装备名, 装备属性 } from "#/types";
import {
    乘员结算顺序,
    摩托化卡车比例,
    摩托化速度,
    民兵属性,
    营折算人数,
    陆军装备属性表,
} from "#/types";

/** 聚合所需的军队字段（装备数量列 + 士兵数量） */
export type 军队属性输入 = Pick<
    Army,
    | "士兵数量"
    | "步兵装备"
    | "卡车"
    | "两栖坦克"
    | "轻型坦克"
    | "中型坦克"
    | "重型坦克"
    | "现代坦克"
    | "装甲运兵车"
    | "两栖装甲运兵车"
    | "坦克歼击车"
    | "自行防空车"
    | "野战炮"
    | "火炮"
    | "火箭炮"
    | "列车炮"
>;

/** 有效装备数表（4.1 乘员咬合结算产物） */
type 有效装备数表 = Partial<Record<陆军装备名, number>>;

/** 4.1 有效装备数（乘员咬合）：非步兵装备按结算顺序占用士兵，余者按持枪/无枪划入步兵 */
function 结算有效装备(军队: 军队属性输入): {
    有效装备数: 有效装备数表;
    持枪步兵: number;
    无枪士兵: number;
} {
    let 剩余士兵 = Math.max(0, 军队.士兵数量);
    const 有效装备数: 有效装备数表 = {};

    for (const 装备名 of 乘员结算顺序) {
        const 属性 = 陆军装备属性表[装备名];
        const 持有数 = Math.max(0, 军队[装备名] ?? 0);
        if (持有数 <= 0) {
            有效装备数[装备名] = 0;
            continue;
        }
        const 有效数 = Math.min(持有数, Math.floor(剩余士兵 / 属性.乘员数));
        有效装备数[装备名] = 有效数;
        剩余士兵 -= 有效数 * 属性.乘员数;
    }

    const 持枪步兵 = Math.min(Math.max(0, 军队.步兵装备), 剩余士兵);
    const 无枪士兵 = 剩余士兵 - 持枪步兵;
    有效装备数["步兵装备"] = 持枪步兵;

    return { 有效装备数, 持枪步兵, 无枪士兵 };
}

/** 4.2 加和属性：软攻/硬攻/突破/防御/HP/宽度按件数加和 */
function 加和面板属性(
    有效装备数: 有效装备数表,
    持枪步兵: number,
    无枪士兵: number,
): Pick<军队面板, "软攻" | "硬攻" | "突破" | "防御" | "HP" | "宽度"> {
    let 软攻 = 0;
    let 硬攻 = 0;
    let 突破 = 0;
    let 防御 = 0;
    let HP = 0;
    let 宽度 = 0;

    const 加和单件 = (属性: 装备属性, 数量: number) => {
        软攻 += 属性.软攻 * 数量;
        硬攻 += 属性.硬攻 * 数量;
        突破 += 属性.突破 * 数量;
        防御 += 属性.防御 * 数量;
        HP += 属性.HP * 数量;
        宽度 += 属性.宽度 * 数量;
    };

    for (const 装备名 of 乘员结算顺序) {
        加和单件(陆军装备属性表[装备名], 有效装备数[装备名] ?? 0);
    }
    加和单件(陆军装备属性表["步兵装备"], 持枪步兵);
    加和单件(民兵属性, 无枪士兵);

    return { 软攻, 硬攻, 突破, 防御, HP, 宽度 };
}

/** 4.3 平均属性（组织度 / 硬度），乘员总和供 4.4 加权复用 */
function 计算平均属性(
    有效装备数: 有效装备数表,
    持枪步兵: number,
    无枪士兵: number,
    士兵数量: number,
): { 组织度: number; 硬度: number; 乘员总和: number } {
    let 组织度加权总和 = 0;
    let 单位数总和 = 0;
    let 硬度乘员总和 = 0;
    let 乘员总和 = 0;

    const 平均单件 = (属性: 装备属性, 有效数: number) => {
        if (有效数 <= 0) return;
        const 乘员 = 有效数 * 属性.乘员数;
        const 单位数 = 乘员 / 营折算人数;
        组织度加权总和 += 属性.组织度 * 单位数;
        单位数总和 += 单位数;
        硬度乘员总和 += 属性.硬度 * 乘员;
        乘员总和 += 乘员;
    };

    for (const 装备名 of 乘员结算顺序) {
        平均单件(陆军装备属性表[装备名], 有效装备数[装备名] ?? 0);
    }
    平均单件(陆军装备属性表["步兵装备"], 持枪步兵);
    平均单件(民兵属性, 无枪士兵);

    const 组织度 = 单位数总和 > 0 ? 组织度加权总和 / 单位数总和 : 0;
    const 硬度 = 士兵数量 > 0 ? 硬度乘员总和 / 士兵数量 : 0;

    return { 组织度, 硬度, 乘员总和 };
}

/** 4.4 装甲 / 穿甲（40-60 公式，防单件重坦 exploit） */
function 计算装甲与穿甲(
    有效装备数: 有效装备数表,
    乘员总和: number,
): { 装甲: number; 穿甲: number } {
    let 最高装甲 = 0;
    let 最高穿甲 = 0;
    let 装甲加权总和 = 0;
    let 穿甲加权总和 = 0;

    for (const 装备名 of 乘员结算顺序) {
        const 有效数 = 有效装备数[装备名] ?? 0;
        if (有效数 <= 0) continue;
        const 属性 = 陆军装备属性表[装备名];
        const 乘员 = 有效数 * 属性.乘员数;
        最高装甲 = Math.max(最高装甲, 属性.装甲);
        最高穿甲 = Math.max(最高穿甲, 属性.穿甲);
        装甲加权总和 += 属性.装甲 * 乘员;
        穿甲加权总和 += 属性.穿甲 * 乘员;
    }

    const 装甲 = 乘员总和 > 0 ? 0.4 * 最高装甲 + 0.6 * (装甲加权总和 / 乘员总和) : 0;
    const 穿甲 = 乘员总和 > 0 ? 0.4 * 最高穿甲 + 0.6 * (穿甲加权总和 / 乘员总和) : 0;

    return { 装甲, 穿甲 };
}

/** 4.5 速度（最慢单位拖全师 + 全员摩托化判定） */
function 计算行军速度(
    军队: 军队属性输入,
    有效装备数: 有效装备数表,
    持枪步兵: number,
    无枪士兵: number,
): { 速度: number; 是否摩托化: boolean } {
    const 士兵总数 = Math.max(0, 军队.士兵数量);
    const 是否摩托化 = 士兵总数 > 0 && 军队.卡车 >= 士兵总数 * 摩托化卡车比例;

    let 速度 = Infinity;
    for (const 装备名 of 乘员结算顺序) {
        const 有效数 = 有效装备数[装备名] ?? 0;
        if (有效数 <= 0) continue;
        速度 = Math.min(速度, 陆军装备属性表[装备名].速度);
    }

    const 步兵人数 = 持枪步兵 + 无枪士兵;
    if (步兵人数 > 0 && !是否摩托化) {
        // 步兵（含民兵）徒步行军 4km/h，拖慢全师
        速度 = Math.min(速度, 民兵属性.速度);
    }
    if (步兵人数 > 0 && 是否摩托化) {
        // 摩托化：步兵不再参与最慢判定，但全师速度不超过卡车速度
        速度 = Math.min(速度, 摩托化速度);
    }
    if (!Number.isFinite(速度)) 速度 = 0; // 空军队

    return { 速度, 是否摩托化 };
}

/**
 * 聚合军队面板（4.1~4.5 完整实现）
 * 空军/弹药为第一阶段预留，不参与聚合（TODO(第二阶段): 空军支援挂载点）
 */
export function 聚合军队面板(军队: 军队属性输入): 军队面板 {
    // ---- 4.1 有效装备数（乘员咬合）----
    const { 有效装备数, 持枪步兵, 无枪士兵 } = 结算有效装备(军队);

    // ---- 4.2 加和属性 ----
    const 加和属性 = 加和面板属性(有效装备数, 持枪步兵, 无枪士兵);

    // ---- 4.3 平均属性（组织度 / 硬度）----
    const { 组织度, 硬度, 乘员总和 } = 计算平均属性(
        有效装备数,
        持枪步兵,
        无枪士兵,
        军队.士兵数量,
    );

    // ---- 4.4 装甲 / 穿甲（40-60 公式，防单件重坦 exploit）----
    const { 装甲, 穿甲 } = 计算装甲与穿甲(有效装备数, 乘员总和);

    // ---- 4.5 速度（最慢单位拖全师 + 全员摩托化判定）----
    const { 速度, 是否摩托化 } = 计算行军速度(军队, 有效装备数, 持枪步兵, 无枪士兵);

    return {
        软攻: 加和属性.软攻,
        硬攻: 加和属性.硬攻,
        突破: 加和属性.突破,
        防御: 加和属性.防御,
        装甲,
        穿甲,
        组织度,
        HP: 加和属性.HP,
        宽度: 加和属性.宽度,
        速度,
        硬度,
        有效装备数,
        持枪步兵,
        无枪士兵,
        是否摩托化,
    };
}

/** HP 阶梯衰减（6.6）：每掉 10% HP 输出降一档 */
export function 计算HP衰减系数(当前HP比例: number): number {
    const 比例 = Math.max(0, Math.min(1, 当前HP比例));
    return Math.floor(比例 * 10) / 10;
}

/** 经验修正（6.8）：1 + min(上限, 经验值 ÷ 除数) */
export function 计算经验修正(经验值: number, 上限: number, 除数: number): number {
    return 1 + Math.min(上限, Math.max(0, 经验值) / 除数);
}
