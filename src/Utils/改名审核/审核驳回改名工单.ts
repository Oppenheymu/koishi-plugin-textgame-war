import { 获取待审核工单 } from "./获取待审核工单";

export function 审核驳回改名工单(工单编号: number, 原因?: string): string {
    const 工单 = 获取待审核工单(工单编号);
    工单.状态 = "已驳回";

    const 规范原因 = 原因?.trim();
    if (规范原因) {
        工单.驳回原因 = 规范原因;
    } else {
        delete 工单.驳回原因;
    }

    return 工单.驳回原因
        ? `改名工单 #${工单编号} 已驳回，原因：${工单.驳回原因}`
        : `改名工单 #${工单编号} 已驳回`;
}
